package com.studentresults.database;

import com.studentresults.security.PasswordUtil;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public final class Database {
    private final String jdbcUrl;

    public Database(String jdbcUrl) {
        this.jdbcUrl = jdbcUrl;
    }

    public static Database production() {
        String configured = System.getenv("SRM_DATA_DIR");
        Path dataDirectory = configured == null || configured.isBlank()
                ? Path.of("data").toAbsolutePath()
                : Path.of(configured).toAbsolutePath();
        try {
            Files.createDirectories(dataDirectory);
        } catch (Exception exception) {
            throw new IllegalStateException("Could not create the data directory", exception);
        }
        return new Database("jdbc:h2:file:" + dataDirectory.resolve("student-results").toString().replace('\\', '/') + ";AUTO_SERVER=TRUE");
    }

    public Connection connection() throws SQLException {
        try {
            Class.forName("org.h2.Driver");
        } catch (ClassNotFoundException exception) {
            throw new IllegalStateException("H2 JDBC driver is missing", exception);
        }
        return DriverManager.getConnection(jdbcUrl, "sa", "");
    }

    public void initialize() {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        email VARCHAR(120) NOT NULL UNIQUE,
                        password_hash VARCHAR(255) NOT NULL,
                        password_salt VARCHAR(255) NOT NULL,
                        full_name VARCHAR(100) NOT NULL,
                        role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
                        roll_number VARCHAR(30) UNIQUE,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                    """);
            migrateUsernameToEmail(connection, statement);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS results (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        student_id BIGINT NOT NULL,
                        subject VARCHAR(80) NOT NULL,
                        marks INT NOT NULL,
                        max_marks INT NOT NULL,
                        exam_name VARCHAR(80) NOT NULL,
                        academic_year VARCHAR(20) NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        CONSTRAINT fk_student FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
                        CONSTRAINT valid_marks CHECK (marks >= 0 AND max_marks > 0 AND marks <= max_marks)
                    )
                    """);
            statement.execute("""
                    CREATE UNIQUE INDEX IF NOT EXISTS unique_student_result
                    ON results(student_id, subject, exam_name, academic_year)
                    """);
            seedIfEmpty(connection);
        } catch (SQLException exception) {
            throw new IllegalStateException("Could not initialize the database", exception);
        }
    }

    private void seedIfEmpty(Connection connection) throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery("SELECT COUNT(*) FROM users")) {
            resultSet.next();
            if (resultSet.getInt(1) > 0) return;
        }

        insertUser(connection, "admin@school.com", "admin123", "Aarav Administrator", "ADMIN", null);
        insertUser(connection, "teacher@school.com", "teacher123", "Tanya Teacher", "TEACHER", null);
        long studentId = insertUser(connection, "student@school.com", "student123", "Riya Sharma", "STUDENT", "SRM-001");

        String sql = "INSERT INTO results (student_id, subject, marks, max_marks, exam_name, academic_year) VALUES (?, ?, ?, ?, ?, ?)";
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            Object[][] rows = {
                    {studentId, "Mathematics", 88, 100, "Semester 1", "2025-26"},
                    {studentId, "Science", 92, 100, "Semester 1", "2025-26"},
                    {studentId, "English", 81, 100, "Semester 1", "2025-26"}
            };
            for (Object[] row : rows) {
                for (int index = 0; index < row.length; index++) statement.setObject(index + 1, row[index]);
                statement.addBatch();
            }
            statement.executeBatch();
        }
    }

    private void migrateUsernameToEmail(Connection connection, Statement statement) throws SQLException {
        boolean hasUsername = hasColumn(connection, "USERNAME");
        boolean hasEmail = hasColumn(connection, "EMAIL");
        if (hasUsername && !hasEmail) {
            statement.execute("ALTER TABLE users RENAME COLUMN username TO email");
        }
        statement.executeUpdate("""
                UPDATE users SET email = CASE LOWER(email)
                    WHEN 'admin' THEN 'admin@school.com'
                    WHEN 'teacher' THEN 'teacher@school.com'
                    WHEN 'student' THEN 'student@school.com'
                    ELSE CONCAT(LOWER(email), '@school.local')
                END
                WHERE email NOT LIKE '%@%'
                """);
    }

    private boolean hasColumn(Connection connection, String columnName) throws SQLException {
        try (ResultSet columns = connection.getMetaData().getColumns(null, null, "USERS", columnName)) {
            return columns.next();
        }
    }

    private long insertUser(Connection connection, String email, String password, String fullName,
                            String role, String rollNumber) throws SQLException {
        String salt = PasswordUtil.newSalt();
        String sql = "INSERT INTO users (email, password_hash, password_salt, full_name, role, roll_number) VALUES (?, ?, ?, ?, ?, ?)";
        try (PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, email);
            statement.setString(2, PasswordUtil.hash(password, salt));
            statement.setString(3, salt);
            statement.setString(4, fullName);
            statement.setString(5, role);
            statement.setString(6, rollNumber);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                keys.next();
                return keys.getLong(1);
            }
        }
    }
}
